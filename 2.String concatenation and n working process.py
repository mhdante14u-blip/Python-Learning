# 3 ways do make space in the code and + sign is for to connect or concatenation
# 1st way :
# After writing one sentence or a word of line end of double quotation mark put a space, for the multiple sentences just add the space at end of the word or the sentences not for the last sentence and connect or concatenation with + sign and write a new sentence or word but all has to be in one same line inside using  the one parentheses()

