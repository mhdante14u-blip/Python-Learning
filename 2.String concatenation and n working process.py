# 2nd way :

# After writing one sentence or a word of line end of double quotation mark do not put a or any space instead use + sign to connect or concatenation a new sentence or word and while writing inside the opening double quotation mark put a space and then write the new sentence or the word but all has to be in one same line inside using the one parentheses()

